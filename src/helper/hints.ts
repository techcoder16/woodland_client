/** Looks up an explanation for a plain-text heading, label or badge. */
export function getHint(text: unknown): string | undefined {
  const plain = Array.isArray(text) ? text.filter((t) => typeof t === "string").join("") : text;
  if (typeof plain !== "string") return undefined;
  return HINTS[plain.trim().replace(/\s*\*$/, "").toLowerCase()];
}
